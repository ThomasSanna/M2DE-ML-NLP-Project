import uuid
from enum import StrEnum
from typing import TYPE_CHECKING

from pgvector.sqlalchemy import HALFVEC
from sqlalchemy import Enum, Index, Integer, String, Text
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import Base, TimestampMixin

if TYPE_CHECKING:
    from app.models.feedback import Feedback

# Vector dimension of BAAI/bge-multilingual-gemma2 (university server).
# Beyond 2000 dimensions, the pgvector HNSW index requires `halfvec` (float16, max 4000).
EMBEDDING_DIM = 3584


def str_enum(enum_cls: type[StrEnum]) -> Enum:
    """Enum stored as VARCHAR + CHECK (easier to evolve than a Postgres ENUM type)."""
    return Enum(
        enum_cls,
        native_enum=False,
        create_constraint=True,
        length=32,
        values_callable=lambda members: [m.value for m in members],
        validate_strings=True,
    )


class KnowledgeSource(StrEnum):
    GLPI_HISTORY = "glpi_history"  # Q/A pair from the GLPI history (or the synthetic dataset)
    LLM = "llm"  # answer generated by the pipeline
    TECHNICIAN = "technician"  # answer written or corrected by a technician


class KnowledgeStatus(StrEnum):
    ACTIVE = "active"
    TO_REVIEW = "to_review"  # poorly rated: to be reviewed by a technician
    ARCHIVED = "archived"


class Knowledge(TimestampMixin, Base):
    """A memory "knowledge" entry: an indexed question/answer pair."""

    __tablename__ = "knowledge"

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid.uuid4)
    question: Mapped[str] = mapped_column(Text)
    answer: Mapped[str] = mapped_column(Text)
    category: Mapped[str | None] = mapped_column(String(64))
    source: Mapped[KnowledgeSource] = mapped_column(str_enum(KnowledgeSource))
    status: Mapped[KnowledgeStatus] = mapped_column(
        str_enum(KnowledgeStatus), default=KnowledgeStatus.ACTIVE, index=True
    )
    glpi_ticket_id: Mapped[int | None] = mapped_column(Integer, index=True)
    # Number of times the entry was used to build an answer.
    reuse_count: Mapped[int] = mapped_column(Integer, default=0, server_default="0")
    # Embedding of the question: it is what gets matched against new requests.
    embedding: Mapped[list[float]] = mapped_column(HALFVEC(EMBEDDING_DIM))

    feedbacks: Mapped[list["Feedback"]] = relationship(
        back_populates="knowledge", cascade="all, delete-orphan", passive_deletes=True
    )

    __table_args__ = (
        Index(
            "ix_knowledge_embedding_hnsw",
            "embedding",
            postgresql_using="hnsw",
            postgresql_ops={"embedding": "halfvec_cosine_ops"},
        ),
    )
