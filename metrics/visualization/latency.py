"""Latency: where the time of a run goes, call by call."""

import pandas as pd

from i18n import number, t
from load import Metrics, answered
from render import (
    INK,
    KIND_COLORS,
    NEUTRAL,
    SURFACE,
    Chart,
    Section,
    Table,
    Tabs,
    boxes,
    canvas,
    chart,
    histogram,
    legend,
)
from stats import cell_ms, fmt_ms, fmt_p95, fmt_pct, note

KINDS = ("embed", "vector_search", "rerank", "llm", "web_search")


def build(metrics: Metrics) -> Section:
    calls = metrics.calls
    done = answered(metrics.runs)
    charts: list[Chart | Tabs] = []
    if not done.empty:
        charts.append(_breakdown(done, calls))
        typical = _typical(done)
        if (calls["run_id"] == typical["run_id"]).any():
            charts.append(_timeline(typical, calls))
    ok = calls[calls["status"] == "ok"]
    if not ok.empty:
        charts.append(_by_kind(calls, ok))
    gaps = calls["gap_ms"].dropna()
    if not gaps.empty:
        charts.append(
            histogram(
                gaps,
                xlabel=t("ms from the end of a call to the start of the next"),
                ylabel=t("gaps"),
                caption=t("Gaps between consecutive calls of a run"),
                reading=t(
                    "Time the API spends between two remote calls of the same run: building the"
                    " next prompt, database access, parsing. Values near zero mean the API adds"
                    " almost nothing to the model and search times."
                ),
            )
        )
    speed = calls["tokens_per_s"].dropna()
    if not speed.empty:
        charts.append(
            histogram(
                speed,
                xlabel=t("completion tokens per second, prefill included"),
                ylabel=t("model calls"),
                caption=t("Generation speed of successful model calls"),
                reading=t(
                    "Tokens generated by a call divided by its duration. The duration includes"
                    " reading the prompt (prefill), so a long prompt lowers this speed even when"
                    " the model generates at the same pace."
                ),
                color=KIND_COLORS["llm"],
            )
        )
    return Section(
        t("Latency"),
        [_shares(done, calls), _slowest(calls), _gap(gaps), _speed(speed)],
        charts,
        [Table(t("Duration per call kind"), _per_kind(calls))],
    )


def _by_kind(calls: pd.DataFrame, ok: pd.DataFrame) -> Tabs:
    """Every call kind side by side, then the duration spread of each kind on its own."""
    kinds = [kind for kind in KINDS if (ok["kind"] == kind).any()]
    meaning = {
        "embed": t("embedding the question"),
        "vector_search": t("searching the memory"),
        "rerank": t("scoring the memory candidates"),
        "llm": t("the language model, one call per agent step"),
        "web_search": t("an Exa search"),
    }
    every = boxes(
        [(kind, ok.loc[ok["kind"] == kind, "duration_ms"] / 1000) for kind in kinds],
        xlabel=t("call duration (s)"),
        caption=t("Duration of successful calls, by kind"),
        reading=t(
            "One row per kind of remote call, successful calls only. A row near zero costs almost"
            " nothing; choose a kind above to see how its durations spread."
        ),
        dots=t("Each dot is one call."),
    )
    options = [(t("All kinds"), every)]
    for kind in kinds:
        durations = ok.loc[ok["kind"] == kind, "duration_ms"]
        median, p95 = float(durations.median()), float(durations.quantile(0.95))
        # Seconds for slow kinds, milliseconds for those that take a few ms.
        scale = 1000 if median >= 1000 else 1
        options.append(
            (
                kind,
                histogram(
                    durations / scale,
                    xlabel=t("duration (s)") if scale == 1000 else t("duration (ms)"),
                    ylabel=t("calls"),
                    caption=t("Duration of {kind} calls", kind=kind),
                    reading=t(
                        "Duration of every successful {kind} call ({meaning}). Successful calls:"
                        " {ok}; failed calls, left out: {failed}. Dashed lines: median and p95.",
                        kind=kind,
                        meaning=meaning[kind],
                        ok=len(durations),
                        failed=int(((calls["kind"] == kind) & (calls["status"] != "ok")).sum()),
                    ),
                    color=KIND_COLORS[kind],
                    markers=[
                        (median / scale, t("median {value}", value=fmt_ms(median))),
                        (p95 / scale, t("p95 {value}", value=fmt_ms(p95))),
                    ],
                ),
            )
        )
    return Tabs(options)


def _typical(done: pd.DataFrame) -> pd.Series:
    """The answered run whose total is closest to the median total."""
    distance = (done["total_ms"] - done["total_ms"].median()).abs()
    return done.loc[distance.idxmin()]


def _shares(done: pd.DataFrame, calls: pd.DataFrame) -> str:
    if done.empty:
        return t("No answered run: no latency breakdown.")
    run = _typical(done)
    total = float(run["total_ms"])
    spent = calls[calls["run_id"] == run["run_id"]].groupby("kind")["duration_ms"].sum()
    shares = sorted(((str(k), float(v) / total) for k, v in spent.items()), key=lambda p: -p[1])
    parts = [f"{kind} {fmt_pct(share)}" for kind, share in shares]
    parts.append(f"{t('other')} {fmt_pct(float(run['overhead_ms']) / total)}")
    median = float(done["total_ms"].median())
    return t(
        "The run closest to the median total ({total}) spends: {shares}.",
        total=fmt_ms(median),
        shares=", ".join(parts),
    )


def _slowest(calls: pd.DataFrame) -> str:
    ok = calls[calls["status"] == "ok"]
    if ok.empty:
        return t("No successful call in the data.")
    medians = ok.groupby("kind")["duration_ms"].median()
    kind = str(medians.idxmax())
    n = int((ok["kind"] == kind).sum())
    return t(
        "Slowest call kind by median duration: {kind}, {duration} ({note}).",
        kind=kind,
        duration=fmt_ms(medians[kind]),
        note=note(n),
    )


def _gap(gaps: pd.Series) -> str:
    if gaps.empty:
        return t("No consecutive calls in the data.")
    return t(
        "Median gap between consecutive calls: {gap} ({note}).",
        gap=fmt_ms(gaps.median()),
        note=note(len(gaps)),
    )


def _speed(speed: pd.Series) -> str:
    if speed.empty:
        return t("No successful model call in the data.")
    return t(
        "Median generation speed: {speed} tokens/s, prefill included ({note}).",
        speed=number(speed.median()),
        note=note(len(speed)),
    )


def _per_kind(calls: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for kind in KINDS:
        of_kind = calls[calls["kind"] == kind]
        if of_kind.empty:
            continue
        ok = of_kind.loc[of_kind["status"] == "ok", "duration_ms"]
        rows.append(
            (
                kind,
                len(of_kind),
                int((of_kind["status"] != "ok").sum()),
                cell_ms(ok.median()) if not ok.empty else "-",
                fmt_p95(ok.quantile(0.95) if not ok.empty else float("nan"), len(ok)),
                cell_ms(ok.max()) if not ok.empty else "-",
            )
        )
    columns = [t("kind"), t("calls"), t("failed"), t("median"), t("p95"), t("max")]
    return pd.DataFrame(rows, columns=columns)


def _breakdown(done: pd.DataFrame, calls: pd.DataFrame) -> Chart:
    per_run = (
        calls[calls["run_id"].isin(done["run_id"])]
        .pivot_table(index="run_id", columns="kind", values="duration_ms", aggfunc="sum")
        .reindex(done["run_id"])
        .fillna(0.0)
    )
    per_run["other"] = done.set_index("run_id")["overhead_ms"]
    means = per_run.groupby(done.set_index("run_id")["config_id"]).mean() / 1000
    means = means.sort_index(key=lambda ids: ids.str[1:].astype(int))
    fig, ax = canvas(height=0.5 * len(means) + 1.4, grid="x")
    left = pd.Series(0.0, index=means.index)
    for kind in (*KINDS, "other"):
        if kind in means:
            ax.barh(
                means.index,
                means[kind],
                left=left,
                color=KIND_COLORS[kind],
                label=t("other") if kind == "other" else kind,
                height=0.6,
                edgecolor=SURFACE,
                linewidth=1.2,
            )
            left = left + means[kind]
    ax.invert_yaxis()
    ax.set_xlabel(t("seconds per answered run (mean)"))
    legend(ax)
    return chart(
        fig,
        t("Mean time per answered run by call kind, per configuration (sums to the mean total)"),
        t(
            "Each bar is the mean answered run of a configuration, cut by what spent the time."
            " embed: embedding the question; vector_search: searching the memory; rerank:"
            " scoring the memory candidates; llm: the language model; web_search: Exa; other:"
            " time outside remote calls (prompt building, database, parsing)."
        ),
    )


def _timeline(run: pd.Series, calls: pd.DataFrame) -> Chart:
    steps = calls[calls["run_id"] == run["run_id"]].sort_values("seq")
    fig, ax = canvas(height=0.35 * len(steps) + 1.2, grid="x")
    labels = []
    for i, call in enumerate(steps.itertuples()):
        ax.barh(
            i,
            call.duration_ms / 1000,
            left=call.start_ms / 1000,
            color=KIND_COLORS.get(str(call.kind), NEUTRAL),
            height=0.6,
        )
        labels.append(
            str(call.kind)
            if pd.isna(call.step)
            else t("{kind} (step {step})", kind=call.kind, step=call.step)
        )
    ax.axvline(float(run["total_ms"]) / 1000, color=INK, linewidth=1, linestyle="--")
    ax.set_yticks(range(len(labels)), labels)
    ax.invert_yaxis()
    ax.set_xlabel(t("seconds since the run started"))
    return chart(
        fig,
        t(
            "Timeline of the run closest to the median total ({total}): {config}, {started} UTC",
            total=fmt_ms(run["total_ms"]),
            config=run["config_id"],
            started=f"{run['started_at']:%Y-%m-%d %H:%M}",
        ),
        t(
            "Each bar is one call of this run, from its start to its end, in order. Space between"
            " two bars is time spent in the API itself; the dashed line marks the answer."
        ),
    )
